#!/usr/bin/env bash
# =============================================================
# Lab 1：IAM 群組、使用者（主控台密碼 + 首次登入重設）、EC2 角色（SSM）
# 執行身分：saa-admin（Lab 0 建立的管理員），不要用 root
# =============================================================
source "$(dirname "$0")/00-env.sh"
DEV_GROUP="${PREFIX}-developers"
DEV_USER="${PREFIX}-dev-user"

log "建立群組 ${DEV_GROUP} 並附加唯讀政策（最小權限示範）"
aws iam create-group --group-name "$DEV_GROUP" >/dev/null
for p in AmazonEC2ReadOnlyAccess AmazonS3ReadOnlyAccess; do
  aws iam attach-group-policy --group-name "$DEV_GROUP" \
    --policy-arn "arn:aws:iam::aws:policy/$p"
done

log "建立使用者 ${DEV_USER} 並加入群組（不建立存取金鑰）"
aws iam create-user --user-name "$DEV_USER" >/dev/null
aws iam add-user-to-group --user-name "$DEV_USER" --group-name "$DEV_GROUP"

log "主控台密碼：隨機產生、首次登入必須變更（等同主控台的 Autogenerated + 需要重設密碼）"
# 主控台勾選「下次登入時建立新密碼」會自動附加 IAMUserChangePassword；CLI 要自己附加
aws iam attach-user-policy --user-name "$DEV_USER" \
  --policy-arn arn:aws:iam::aws:policy/IAMUserChangePassword
PW="$(gen_password)"
aws iam create-login-profile --user-name "$DEV_USER" --password "$PW" --password-reset-required >/dev/null
print_console_login "$DEV_USER" "$PW"
unset PW

log "建立 EC2 角色 ${PREFIX}-ec2-ssm-role（信任 ec2.amazonaws.com）"
aws iam create-role --role-name "${PREFIX}-ec2-ssm-role" \
  --description "Allows EC2 instances to call AWS services like CloudWatch and Systems Manager on your behalf." \
  --assume-role-policy-document "file://$(dirname "$0")/../policies/ec2-trust-policy.json" >/dev/null
aws iam attach-role-policy --role-name "${PREFIX}-ec2-ssm-role" \
  --policy-arn arn:aws:iam::aws:policy/AmazonSSMManagedInstanceCore

log "建立 Instance Profile 並放入角色（主控台會自動建同名設定檔；CLI 要自己建）"
aws iam create-instance-profile --instance-profile-name "${PREFIX}-ec2-ssm-role" >/dev/null
aws iam add-role-to-instance-profile --instance-profile-name "${PREFIX}-ec2-ssm-role" \
  --role-name "${PREFIX}-ec2-ssm-role"

log "驗證"
aws iam list-attached-group-policies --group-name "$DEV_GROUP" --output table
aws iam get-login-profile --user-name "$DEV_USER" \
  --query 'LoginProfile.[UserName,PasswordResetRequired]' --output table
aws iam list-mfa-devices --user-name "$DEV_USER" --query 'length(MFADevices)' --output text \
  | xargs -I{} echo "MFA 裝置數量：{}（本 Lab 未指派，正式環境請指派）"
aws iam get-role --role-name "${PREFIX}-ec2-ssm-role" --query 'Role.AssumeRolePolicyDocument' --output json
